import { useEffect, useRef, type FormEvent, type KeyboardEvent } from 'react'
import Markdown from 'react-markdown'
import type { Role } from '../api'

export interface ChatMessage {
  role: Role
  content: string
}

interface ChatWindowProps {
  messages: ChatMessage[]
  loading: boolean
  savingNote: boolean
  draft: string
  models: string[]
  model: string
  onModelChange: (value: string) => void
  onDraftChange: (value: string) => void
  onSend: () => void
  onAddNote: () => void
}

export default function ChatWindow({
  messages,
  loading,
  savingNote,
  draft,
  models,
  model,
  onModelChange,
  onDraftChange,
  onSend,
  onAddNote,
}: ChatWindowProps) {
  const bottomRef = useRef<HTMLDivElement>(null)
  // Either the LLM is answering or a note is being saved: the composer is locked.
  const busy = loading || savingNote
  // "…" is shown until the first piece of the reply arrives; after that the reply itself grows.
  const last = messages[messages.length - 1]
  const waitingForReply = loading && last?.role !== 'assistant'

  // Keep the latest message in view (no smooth animation while the reply is streaming).
  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: loading ? 'auto' : 'smooth' })
  }, [messages, loading])

  function handleSubmit(event: FormEvent) {
    event.preventDefault()
    if (!busy && draft.trim()) onSend()
  }

  function handleKeyDown(event: KeyboardEvent<HTMLTextAreaElement>) {
    // Enter sends, Shift+Enter inserts a new line.
    if (event.key === 'Enter' && !event.shiftKey) handleSubmit(event)
  }

  return (
    <section className="chat">
      {models.length > 0 && (
        <div className="model-bar">
          <label>
            Modèle{' '}
            <select
              className="model-select"
              value={model}
              onChange={(e) => onModelChange(e.target.value)}
              disabled={busy}
            >
              {models.map((m) => (
                <option key={m} value={m}>
                  {m}
                </option>
              ))}
            </select>
          </label>
        </div>
      )}
      <div className="messages">
        {messages.length === 0 && !loading && (
          <p className="muted center">Pose ta première question à Study Buddy.</p>
        )}
        {messages.map((m, i) => {
          if (m.role === 'system-notification') {
            return (
              <div key={i} className="notification">
                {m.content}
              </div>
            )
          }
          if (m.role === 'note') {
            // Personal note: shown in the chat, but the backend never sends it to the LLM.
            return (
              <div key={i} className="note">
                <span className="note-label">Note personnelle</span>
                {m.content}
              </div>
            )
          }
          if (m.role === 'summary' || m.role === 'quiz') {
            // Generated by the tutor and stored in the DB: shown as a labelled card.
            return (
              <div key={i} className={m.role}>
                <span className="extra-label">
                  {m.role === 'quiz' ? 'Question de révision' : 'Résumé de la conversation'}
                </span>
                <Markdown>{m.content}</Markdown>
              </div>
            )
          }
          return (
            <div key={i} className={`bubble ${m.role}`}>
              {/* The LLM answers in Markdown; user messages are shown as typed. */}
              {m.role === 'assistant' ? <Markdown>{m.content}</Markdown> : m.content}
            </div>
          )
        })}
        {waitingForReply && <div className="bubble assistant typing">…</div>}
        <div ref={bottomRef} />
      </div>
      <form className="composer" onSubmit={handleSubmit}>
        <textarea
          value={draft}
          onChange={(e) => onDraftChange(e.target.value)}
          onKeyDown={handleKeyDown}
          placeholder="Écris ton message…"
          rows={2}
          disabled={busy}
          autoFocus
        />
        <div className="composer-actions">
          <button type="submit" disabled={busy || !draft.trim()}>
            Envoyer
          </button>
          {/* The backend refuses a note in an empty conversation, so the button waits for a first message. */}
          <button
            type="button"
            className="note-button"
            onClick={onAddNote}
            disabled={busy || !draft.trim() || messages.length === 0}
            title="Enregistrée dans la conversation, jamais envoyée au tuteur"
          >
            Ajouter une note
          </button>
        </div>
      </form>
    </section>
  )
}
